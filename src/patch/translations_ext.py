# 数值型 "N samples" 统一规则
import re as _re
_SAMP = _re.compile(r'^(\d+) samples$')


def lookup(s):
    """返回译文；保留项返回 None。"""
    if s in KEEP:
        return None
    if s in EXT:
        return EXT[s]
    m = _SAMP.match(s)
    if m:
        return m.group(1) + ' 样本'
    return None
